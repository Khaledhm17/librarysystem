package library;

// هذه الواجهة تمثل خصائص وسلوكيات الكتاب في نظام المكتبة
public interface Book {
    
    // دالة للحصول على عنوان الكتاب
    String getTitle();

    // دالة للحصول على اسم المؤلف
    String getAuthor();

    // دالة للحصول على رقم ISBN الخاص بالكتاب
    String getISBN();

    // دالة للتحقق مما إذا كان الكتاب متاحاً للإعارة
    boolean isAvailable();

    // دالة لتغيير حالة الكتاب إلى "غير متاح" عند الإعارة
    void borrow();

    // دالة لتغيير حالة الكتاب إلى "متاح" عند الإرجاع
    void returnBook();

    // دالة لتحديد نوع الكتاب (ورقي أو إلكتروني)
    String getType();
}
